    st.write(
        f"**Association Rules:** {len(rules)}"
    )

    st.write(
        f"**Products with Recommendation Rules:** "
        f"{rules['antecedent'].nunique()}"
    )

    st.write(
        f"**Maximum Confidence:** "
        f"{rules['confidence'].max():.2f}%"
    )

    st.write(
        f"**Maximum Lift:** "
        f"{rules['lift'].max():.2f}"
    )

    st.success(
        "The project combines data preprocessing, "
        "association-rule mining and an interactive "
        "recommendation interface."
    )